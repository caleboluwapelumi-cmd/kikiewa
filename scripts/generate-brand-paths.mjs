/**
 * Regenerates components/brand/paths.ts from the SVGs in public/brand/.
 *
 * Run after swapping in new logo files (same names): npm run brand:generate
 *
 * The full-colour logo's fills are mapped to theme tokens, so the inlined
 * logo always matches app/globals.css and components never carry hex values.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const brand = (file) => readFileSync(join(root, "public/brand", file), "utf8");

// Logo fill -> theme token. An unknown colour stops the build rather than
// letting a stray hex value through.
const tones = {
  "#5B0F53": "primary",
  "#8A2174": "secondary",
  "#C868A3": "accent",
};

function parse(svg, file) {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${file}: no viewBox`);
  const paths = [...svg.matchAll(/<path\b([^>]*)\/?>/g)].map(([, attrs]) => {
    const d = attrs.match(/\sd="([^"]+)"/)?.[1];
    const fill = attrs.match(/\sfill="([^"]+)"/)?.[1];
    const rule = attrs.match(/\sfill-rule="([^"]+)"/)?.[1];
    if (!d) throw new Error(`${file}: path without d`);
    if (rule && rule !== "evenodd") throw new Error(`${file}: unexpected fill-rule ${rule}`);
    return { d, fill };
  });
  return { viewBox, paths };
}

function colour(file) {
  const { viewBox, paths } = parse(brand(file), file);
  return {
    viewBox,
    paths: paths.map(({ d, fill }) => {
      const tone = tones[fill?.toUpperCase()];
      if (!tone) throw new Error(`${file}: fill ${fill} is not a brand token`);
      return { tone, d };
    }),
  };
}

function mono(file) {
  const { viewBox, paths } = parse(brand(file), file);
  for (const { fill } of paths) {
    if (fill !== "currentColor") throw new Error(`${file}: mono file has fill ${fill}`);
  }
  return { viewBox, paths: paths.map(({ d }) => d) };
}

const out = `/* Generated by scripts/generate-brand-paths.mjs from public/brand/*.svg.
   Do not edit by hand: swap the SVG files and run \`npm run brand:generate\`. */

export type LogoTone = "primary" | "secondary" | "accent";

/** Full-colour logo (peacock + wordmark). Fills map to theme tokens. */
export const logo: { viewBox: string; paths: { tone: LogoTone; d: string }[] } = ${JSON.stringify(colour("kikiewa-logo.svg"))};

/** One-colour logo, drawn in currentColor. */
export const logoMono: { viewBox: string; paths: string[] } = ${JSON.stringify(mono("kikiewa-logo-mono.svg"))};

/** One-colour peacock mark, drawn in currentColor. */
export const markMono: { viewBox: string; paths: string[] } = ${JSON.stringify(mono("kikiewa-mark-mono.svg"))};
`;

writeFileSync(join(root, "components/brand/paths.ts"), out);
console.log("Wrote components/brand/paths.ts");
