/**
 * npm run db:seed            writes supabase/migrations/…_seed_catalogue.sql
 * npm run db:seed -- --check exits 1 if that file is out of date
 *
 * Builds the catalogue seed from data/site.ts: both branches with their
 * pins, opening hours (from each branch's weekly hours), and every service
 * on the menu plus a "not sure yet" entry per category.
 *
 * Prices that are TBC in data/site.ts are seeded as NULL with payment_mode
 * 'none', so those services book as requests (no payment).
 * Durations that are TBC are seeded as DEFAULT_DURATION_MINS, a scheduling
 * placeholder only (it sets slot length), marked in the SQL.
 *
 * Inserts are ON CONFLICT DO NOTHING: re-running never overwrites prices,
 * durations or hours the business has since set in the database.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { bookPage, isTBC, locations, serviceCategories, serviceMenus } from "../data/site.ts";

export const DEFAULT_DURATION_MINS = 60;
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const SEED_PATH = join(root, "supabase", "migrations", "20261113120200_seed_catalogue.sql");

const DOW = { sunday: 0, monday: 1, tuesday: 2, wednesday: 3, thursday: 4, friday: 5, saturday: 6 };

function sql(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  return `'${String(value).replace(/'/g, "''")}'`;
}

export function buildSeed() {
  const out = [
    "-- GENERATED by scripts/generate-seed.mjs from data/site.ts. Do not edit by hand;",
    "-- change data/site.ts and run `npm run db:seed`.",
    "--",
    "-- ON CONFLICT DO NOTHING throughout: values set later in the database (prices,",
    "-- durations, hours) are never overwritten by a re-run.",
    "",
    "-- Branches",
  ];

  for (const location of locations) {
    out.push(
      "insert into public.branches (slug, name, address, lat, lng, place_id, phone, active) values (" +
        [
          sql(location.id),
          sql(location.title),
          sql(isTBC(location.address) ? null : location.address),
          sql(location.map.lat ?? null),
          sql(location.map.lng ?? null),
          sql(location.map.placeId ?? null),
          sql(isTBC(location.phone) ? null : location.phone),
          "true",
        ].join(", ") +
        ") on conflict (slug) do nothing;",
    );
  }

  out.push("", "-- Opening hours (Lagos time). weekday: 0 = Sunday … 6 = Saturday");
  for (const location of locations) {
    if (isTBC(location.hours)) continue;
    for (const [day, hours] of Object.entries(location.hours)) {
      if (!hours) continue;
      out.push(
        `insert into public.branch_hours (branch_id, weekday, opens, closes) select id, ${DOW[day]}, ${sql(hours.opens)}, ${sql(hours.closes)} from public.branches where slug = ${sql(location.id)} on conflict do nothing;`,
      );
    }
  }

  out.push("", "-- Services (price NULL -> payment_mode 'none': booked as a request, no payment)");
  let sort = 0;
  for (const category of serviceCategories) {
    for (const item of serviceMenus[category.slug]) {
      sort += 10;
      const duration = isTBC(item.durationMins) ? DEFAULT_DURATION_MINS : item.durationMins;
      const price = isTBC(item.priceFrom) ? null : Math.round(item.priceFrom * 100);
      out.push(
        "insert into public.services (slug, category, name, duration_mins, price_kobo, payment_mode, requires_consultation, capacity_per_slot, active, sort) values (" +
          [
            sql(item.slug),
            sql(category.slug),
            sql(item.name),
            sql(duration),
            sql(price),
            sql("none"),
            sql(Boolean(item.requiresConsultation)),
            "1",
            "true",
            String(sort),
          ].join(", ") +
          `) on conflict (slug) do nothing;${isTBC(item.durationMins) ? " -- duration placeholder (TBC)" : ""}`,
      );
    }
    // "Not sure yet": books the category, the team helps choose.
    if (!category.consultationLed) {
      sort += 10;
      out.push(
        "insert into public.services (slug, category, name, duration_mins, price_kobo, payment_mode, requires_consultation, capacity_per_slot, active, sort) values (" +
          [
            sql(category.slug),
            sql(category.slug),
            sql(`${category.name} (${bookPage.service.notSure.toLowerCase()})`),
            sql(DEFAULT_DURATION_MINS),
            "null",
            sql("none"),
            "false",
            "1",
            "true",
            String(sort),
          ].join(", ") +
          ") on conflict (slug) do nothing; -- duration placeholder",
      );
    }
  }
  return out.join("\n") + "\n";
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const seed = buildSeed();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(SEED_PATH, "utf8");
    } catch {
      // missing counts as out of date
    }
    if (current.replace(/\r\n/g, "\n") !== seed) {
      console.error("db:seed: the catalogue seed is out of date. Run `npm run db:seed`.");
      process.exit(1);
    }
    console.log("db:seed: catalogue seed is up to date.");
  } else {
    writeFileSync(SEED_PATH, seed);
    console.log(`db:seed: wrote ${SEED_PATH}`);
  }
}
